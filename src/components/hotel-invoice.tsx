import { Barcode } from "@/components/barcode";
import {
  hotelTotals,
  longDate,
  moneyPlain,
  nightsOf,
  passengerPlain,
  type Trip,
} from "@/lib/trip";

export function HotelInvoice({ trip }: { trip: Trip }) {
  const totals = hotelTotals(trip);
  const nights = nightsOf(trip);

  return (
    <article className="print-sheet overflow-hidden rounded-xl bg-paper text-ink shadow-[0_24px_60px_-28px_rgba(0,0,0,0.55)]">
      <div className="h-2 bg-ink" />
      <div className="px-6 py-7 sm:px-8">
        <header className="flex items-start justify-between gap-4">
          <div>
            <div className="text-sm font-semibold tracking-[0.18em] text-ink uppercase">
              {trip.hotelName}
            </div>
            <div className="mt-1 text-[11px] tracking-[0.16em] text-ink-muted uppercase">
              {trip.hotelCity}
            </div>
          </div>
          <div className="text-right">
            <div className="text-[10px] font-medium tracking-[0.16em] text-ink-muted uppercase">
              Folio
            </div>
            <div className="mt-1 font-mono text-base font-semibold tabular-nums">{trip.folio}</div>
          </div>
        </header>

        <div className="mt-5 h-px bg-ink" />
        <p className="mt-3 text-[11px] font-medium tracking-[0.14em] text-ink-muted uppercase">
          Guest folio · {nights}-night stay
        </p>

        <dl className="mt-5 grid grid-cols-2 gap-x-4 gap-y-5 sm:grid-cols-4">
          <Item label="Guest" value={passengerPlain(trip)} />
          <Item label="Confirmation" value={trip.pnr} />
          <Item label="Room" value={`${trip.room}  ${trip.roomType}`} />
          <Item label="Nights" value={String(nights)} />
          <Item
            label="Check-in"
            value={`${longDate(trip.checkIn)}  ${trip.checkInTime}`}
          />
          <Item
            label="Check-out"
            value={`${longDate(trip.checkOut)}  ${trip.checkOutTime}`}
          />
        </dl>

        <div className="mt-8">
          <div className="flex justify-between text-[10px] font-medium tracking-[0.16em] text-ink-muted uppercase">
            <span>Description</span>
            <span>Amount USD</span>
          </div>
          <div className="mt-2 h-px bg-rule" />
          <Row
            label={`${trip.roomType} × ${nights} nights`}
            amount={moneyPlain(totals.room)}
          />
          <Row label="Tourism fee" amount={moneyPlain(totals.tourism)} />
          <Row
            label={`Value added tax ${(trip.vatRate * 100).toFixed(0)}%`}
            amount={moneyPlain(totals.vat)}
          />
          <Row label="Municipality fee" amount={moneyPlain(totals.muni)} />
          <div className="mt-1 h-px bg-ink" />
          <div className="flex items-end justify-between pt-3">
            <span className="text-sm font-semibold tracking-wide">Total paid</span>
            <span className="font-display text-2xl font-semibold tabular-nums">
              {moneyPlain(totals.total)}
            </span>
          </div>
        </div>

        <div className="mt-6 flex flex-wrap items-center gap-3">
          <span className="rounded-sm bg-forest px-3 py-2 text-[11px] font-semibold tracking-[0.16em] text-forest-fg uppercase">
            Paid in full
          </span>
          <span className="text-sm text-ink-muted">
            Visa ···· {trip.cardLast4} · Auth {trip.authCode}
          </span>
        </div>

        <Barcode value={trip.folio + trip.pnr} className="mt-8 h-9" />

        <p className="mt-5 text-xs leading-relaxed text-ink-muted">{trip.hotelAddress}</p>
        <p className="mt-2 text-[11px] leading-relaxed text-ink-muted">
          Itinerary record generated by Weekfare. Sample document for a one-week stay — not a
          licensed tax invoice from the property.
        </p>
      </div>
    </article>
  );
}

function Item({ label, value }: { label: string; value: string }) {
  return (
    <div>
      <dt className="text-[10px] font-medium tracking-[0.16em] text-ink-muted uppercase">{label}</dt>
      <dd className="mt-1 font-mono text-sm font-medium text-ink">{value}</dd>
    </div>
  );
}

function Row({ label, amount }: { label: string; amount: string }) {
  return (
    <div className="flex items-center justify-between border-b border-rule py-3 text-sm">
      <span>{label}</span>
      <span className="font-mono tabular-nums">{amount}</span>
    </div>
  );
}
